import { createHash, randomBytes } from "node:crypto";
import { closeSync, createReadStream, fstatSync, openSync, statSync, unlinkSync, type ReadStream } from "node:fs";
import { mkdir, open, unlink, type FileHandle } from "node:fs/promises";
import { join, resolve } from "node:path";
import { getEnv } from "../env";
import { AppError } from "../http";
import { logger } from "../logger";

/**
 * Local-filesystem storage for uploaded case documents.
 *
 * - Files live flat under UPLOAD_DIR (default `./storage/uploads`, never inside
 *   `public/`), each addressed by a random server-generated storage key.
 *   User-supplied file names are metadata only and never become path components.
 * - The real file type is detected from magic bytes only (PDF, PNG, JPEG, DOCX);
 *   the client-declared MIME type and the file extension are ignored.
 * - The size limit comes from the `upload.maxSizeMb` setting.
 *
 * Atomicity contract: `storeFile` writes the physical file only. Callers register
 * the file in the database *after* it succeeds and must call `deleteFromDisk` as
 * compensation if that registration fails, so no untracked orphan file remains
 * (see `uploadCaseFile` in `services/case.ts`).
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

const MIME = {
  pdf: "application/pdf",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  jpeg: "image/jpeg",
  png: "image/png",
} as const;

export type AllowedMimeType = (typeof MIME)[keyof typeof MIME];

export interface UploadInput {
  /** Raw file bytes (the caller may already have size-checked them while reading). */
  data: Buffer;
  /** The user-supplied file name: metadata only, never used as a disk path. */
  originalName: string;
}

export interface StoredFile {
  storageKey: string;
  mimeType: AllowedMimeType;
  sizeBytes: number;
  sha256: string;
}

// ---------------------------------------------------------------------------
// Magic-byte type detection
// ---------------------------------------------------------------------------

/** The only types accepted on upload and served on download. */
export const ALLOWED_MIME_TYPES: ReadonlySet<string> = new Set<string>(Object.values(MIME));

/** Fixed signatures at offset 0. */
const SIGNATURES: ReadonlyArray<{ mime: AllowedMimeType; bytes: readonly number[] }> = [
  // "%PDF-": the mandatory PDF header (ISO 32000-1, 7.5.2).
  { mime: MIME.pdf, bytes: [0x25, 0x50, 0x44, 0x46, 0x2d] },
  // The full 8-byte PNG signature.
  { mime: MIME.png, bytes: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] },
  // JPEG: SOI marker followed by the first segment marker.
  { mime: MIME.jpeg, bytes: [0xff, 0xd8, 0xff] },
];

/** ZIP local file header "PK\x03\x04": every OOXML package starts with one. */
const ZIP_LOCAL_HEADER: readonly number[] = [0x50, 0x4b, 0x03, 0x04];

/**
 * The main part of a WordprocessingML package. Spreadsheets, presentations and
 * arbitrary ZIP archives do not contain it, so a bare ZIP is never accepted.
 */
const DOCX_MAIN_PART = Buffer.from("word/document.xml", "latin1");

function startsWith(bytes: Uint8Array, signature: readonly number[]): boolean {
  return bytes.length >= signature.length && signature.every((b, i) => bytes[i] === b);
}

/**
 * Detects the file type from its content.
 *
 * @param bytes The whole file, or at least its first 64 KB. ZIP part names are
 *   stored as plain bytes in each local file header and again in the central
 *   directory at the end of the archive, so passing the whole file also accepts
 *   DOCX files whose `word/document.xml` entry is not near the start.
 * @returns The canonical allowed MIME type, or null when the content is
 *   unrecognised or unsupported (the caller must reject it).
 */
export function detectMimeType(bytes: Uint8Array): AllowedMimeType | null {
  for (const { mime, bytes: signature } of SIGNATURES) {
    if (startsWith(bytes, signature)) return mime;
  }
  if (startsWith(bytes, ZIP_LOCAL_HEADER)) {
    // Zero-copy byte search: no string conversion of a potentially large buffer.
    const view = Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength);
    return view.includes(DOCX_MAIN_PART) ? MIME.docx : null;
  }
  return null;
}

// ---------------------------------------------------------------------------
// Storage keys and paths
// ---------------------------------------------------------------------------

/** Storage keys are exactly 48 lowercase hex characters generated by the server. */
export const STORAGE_KEY_PATTERN = /^[a-f0-9]{48}$/;

export function isValidStorageKey(key: string): boolean {
  return typeof key === "string" && STORAGE_KEY_PATTERN.test(key);
}

/** 24 random bytes give 48 hex characters (192 bits, so keys cannot be guessed). */
function generateStorageKey(): string {
  return randomBytes(24).toString("hex");
}

function storageRoot(): string {
  return resolve(getEnv().UPLOAD_DIR);
}

function errnoCode(error: unknown): string | undefined {
  return (error as NodeJS.ErrnoException | null)?.code;
}

function notFound(): AppError {
  return new AppError(404, "FILE_NOT_FOUND", "فایل مورد نظر یافت نشد.");
}

/** Absolute disk path for a storage key. Rejects malformed keys (path-traversal defence). */
export function filePath(storageKey: string): string {
  if (!isValidStorageKey(storageKey)) {
    throw new AppError(400, "INVALID_STORAGE_KEY", "شناسه فایل نامعتبر است.");
  }
  return join(storageRoot(), storageKey);
}

/** Whether a regular file exists on disk for this key. False for malformed keys. */
export function fileExists(storageKey: string): boolean {
  if (!isValidStorageKey(storageKey)) return false;
  try {
    return statSync(join(storageRoot(), storageKey), { throwIfNoEntry: false })?.isFile() ?? false;
  } catch {
    return false;
  }
}

// ---------------------------------------------------------------------------
// File names
// ---------------------------------------------------------------------------

/** `files.original_name` is varchar(255), which PostgreSQL counts in characters. */
const MAX_NAME_LENGTH = 255;
/** Extensions longer than this are not treated as an extension when truncating. */
const MAX_EXTENSION_LENGTH = 16;

/**
 * Removed from file names: C0/C1 control characters (CR/LF could inject response
 * headers), quotes and angle brackets, and bidi embedding/override/isolate
 * characters (U+202A–U+202E, U+2066–U+2069) that can disguise an extension, as in
 * "invoice\u202Efdp.exe". ZWNJ/ZWJ (U+200C/U+200D) are kept: Persian needs them.
 */
const UNSAFE_NAME_CHARS = /[\u0000-\u001f\u007f-\u009f"<>\u202a-\u202e\u2066-\u2069]/g;

/** Truncates by code points (never splits a surrogate pair) and keeps a short extension. */
function truncateName(name: string, max: number): string {
  const chars = Array.from(name);
  if (chars.length <= max) return name;
  const dot = name.lastIndexOf(".");
  const ext = dot > 0 ? Array.from(name.slice(dot)) : [];
  if (ext.length < 2 || ext.length > MAX_EXTENSION_LENGTH) return chars.slice(0, max).join("").trim();
  return chars.slice(0, max - ext.length).join("").trimEnd() + ext.join("");
}

/**
 * Normalises a user-supplied file name for storage and display as metadata:
 * Unicode NFC, strips any path components and unsafe characters, caps the length.
 * Never returns an empty name.
 */
export function normalizeOriginalName(name: string): string {
  const base = name.normalize("NFC").replace(/\\/g, "/").split("/").pop() ?? "";
  const cleaned = base.replace(UNSAFE_NAME_CHARS, "").trim();
  if (cleaned === "" || cleaned === "." || cleaned === "..") return "file";
  return truncateName(cleaned, MAX_NAME_LENGTH);
}

// ---------------------------------------------------------------------------
// Store / delete / read
// ---------------------------------------------------------------------------

const BYTES_PER_MB = 1024 * 1024;

/** The configured upload limit in MB. Fails closed: a corrupt value never disables it. */
async function maxUploadSizeMb(): Promise<number> {
  // Loaded lazily so the pure helpers above (type detection, key and name checks)
  // can be imported without a database connection being configured.
  const { SETTING_DEFS, getSettingValue } = await import("../services/settings");
  const configured = Number(await getSettingValue("upload.maxSizeMb"));
  return Number.isFinite(configured) && configured > 0 ? configured : SETTING_DEFS["upload.maxSizeMb"].defaultValue;
}

function storageWriteError(error: unknown): AppError {
  logger.error("storage.write_failed", { error });
  return new AppError(500, "STORAGE_ERROR", "خطا در ذخیره فایل.");
}

/**
 * Creates `dest` exclusively (an existing file is never overwritten) and flushes
 * it to disk before returning, so the database never references a file that a
 * crash could still lose. A partially written file is removed.
 */
async function writeNewFile(dest: string, data: Buffer): Promise<void> {
  let handle: FileHandle;
  try {
    handle = await open(dest, "wx", 0o640);
  } catch (error) {
    // Nothing was created by this call (EEXIST included), so nothing to clean up.
    throw storageWriteError(error);
  }
  try {
    await handle.writeFile(data);
    await handle.datasync();
    await handle.close();
  } catch (error) {
    await handle.close().catch(() => undefined);
    await unlink(dest).catch(() => undefined);
    throw storageWriteError(error);
  }
}

/**
 * Validates a file and stores it on disk. Throws an AppError on any validation
 * or I/O failure, leaving no partial file behind.
 *
 * 1. Rejects empty files (400 EMPTY_FILE) and files above `upload.maxSizeMb`
 *    (413 FILE_TOO_LARGE).
 * 2. Detects the real type from magic bytes (400 INVALID_FILE_TYPE otherwise).
 * 3. Computes the SHA-256 of the full content.
 * 4. Writes it under a new random storage key inside UPLOAD_DIR.
 */
export async function storeFile(input: UploadInput): Promise<StoredFile> {
  const sizeBytes = input.data.length;
  if (sizeBytes === 0) {
    throw new AppError(400, "EMPTY_FILE", "فایل خالی است.");
  }
  const maxSizeMb = await maxUploadSizeMb();
  if (sizeBytes > maxSizeMb * BYTES_PER_MB) {
    throw new AppError(413, "FILE_TOO_LARGE", `حجم فایل بیش از ${maxSizeMb} مگابایت مجاز است.`);
  }

  const mimeType = detectMimeType(input.data);
  if (!mimeType) {
    throw new AppError(400, "INVALID_FILE_TYPE", "نوع فایل مجاز نیست. فایل‌های PDF، DOCX، JPG و PNG پذیرفته می‌شوند.");
  }

  const sha256 = createHash("sha256").update(input.data).digest("hex");
  const storageKey = generateStorageKey();
  const root = storageRoot();
  try {
    await mkdir(root, { recursive: true, mode: 0o750 });
  } catch (error) {
    throw storageWriteError(error);
  }
  await writeNewFile(join(root, storageKey), input.data);

  return { storageKey, mimeType, sizeBytes, sha256 };
}

/**
 * Removes a physical file: compensation after a failed database registration, or
 * cleanup of `deleted` lifecycle records. Synchronous; malformed keys and
 * already-missing files are a no-op.
 */
export function deleteFromDisk(storageKey: string): void {
  if (!isValidStorageKey(storageKey)) return;
  try {
    unlinkSync(join(storageRoot(), storageKey));
  } catch (error) {
    if (errnoCode(error) !== "ENOENT") logger.error("storage.delete_failed", { error });
  }
}

/**
 * Opens a stored file for streaming. Throws a safe 404 FILE_NOT_FOUND when the
 * key is malformed or the physical file is missing, so callers never reveal more.
 *
 * The descriptor is opened synchronously: there is no gap between the existence
 * check and the open, and a download already in progress keeps working even if
 * the file is unlinked meanwhile. The returned stream closes the descriptor when
 * it ends, fails or is destroyed.
 */
export function createReadStreamSafe(storageKey: string): ReadStream {
  if (!isValidStorageKey(storageKey)) {
    logger.warn("storage.invalid_storage_key");
    throw notFound();
  }
  const path = join(storageRoot(), storageKey);

  let fd: number;
  try {
    fd = openSync(path, "r");
  } catch (error) {
    const code = errnoCode(error);
    if (code === "ENOENT" || code === "ENOTDIR") throw notFound();
    logger.error("storage.read_failed", { error });
    throw new AppError(500, "STORAGE_ERROR", "خطا در خواندن فایل.");
  }

  let isFile = false;
  try {
    isFile = fstatSync(fd).isFile();
  } catch {
    // Treated as missing below.
  }
  if (!isFile) {
    closeSync(fd);
    throw notFound();
  }
  return createReadStream(path, { fd });
}
